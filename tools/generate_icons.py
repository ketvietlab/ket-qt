#!/usr/bin/env python3
"""Generate the Két Symbol Qt resources from the vendored icons.

Reads third_party/ket-symbol/ (SOURCE.json, ketplus-map.json and svg/) and writes:
  src/icons/generated/ket-symbol.qrc       every vendored SVG, aliased as
                                           :/ket-symbol/<weight>/<size>/<code>.svg
  src/icons/generated/KetSymbolNames.inc   X-macro rows: sizes, weights, codes and the
                                           Lucide -> Két map of KetPlus

The SVGs are copied unedited from a Két Symbol dist and keep their SPDX lines and
CC BY 4.0 licence. To vendor a new release, pass its unpacked dist folder:
  python3 tools/generate_icons.py --dist path/to/KetSymbol-<version>
then update SOURCE.json and run again without --dist. Run with --check to fail when
the committed outputs are stale or the vendored files are incomplete.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "third_party/ket-symbol"
SOURCE_INFO = VENDOR / "SOURCE.json"
MAP = VENDOR / "ketplus-map.json"
SVG = VENDOR / "svg"
LICENSE_TEXT = "LICENSES/CC-BY-4.0.txt"
QRC_OUT = ROOT / "src/icons/generated/ket-symbol.qrc"
INC_OUT = ROOT / "src/icons/generated/KetSymbolNames.inc"
SPDX = "<!-- SPDX-License-Identifier: CC-BY-4.0 -->"


def vendor(dist, sizes, weights):
    """Copy the KetPlus codes of a Két Symbol dist into third_party/ket-symbol."""
    manifest = json.loads((dist / "manifest.json").read_text(encoding="utf-8"))
    if manifest["license"]["id"] != "CC-BY-4.0":
        raise SystemExit(f"unexpected licence {manifest['license']['id']}")
    rows = sorted(({"lucide": r["lucide"], "code": r["code"], "status": r["status"]}
                   for r in manifest["ketplus"]["rows"]), key=lambda r: r["lucide"])
    codes = sorted({r["code"] for r in rows})
    if SVG.exists():
        shutil.rmtree(SVG)
    for size in sizes:
        for weight in weights:
            for code in codes:
                src = dist / "svg" / str(size) / weight / f"{code}.svg"
                dst = SVG / str(size) / weight / f"{code}.svg"
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, dst)
    (VENDOR / "LICENSES").mkdir(parents=True, exist_ok=True)
    # The legal code ends in a blank line; drop it so git diff --check stays clean.
    text = (dist / LICENSE_TEXT).read_text(encoding="utf-8")
    (VENDOR / LICENSE_TEXT).write_text(text.rstrip("\n") + "\n", encoding="utf-8")
    MAP.write_text(json.dumps({"version": manifest["version"], "rows": rows}, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    print(f"vendored {len(codes)} codes x {len(sizes)} sizes x {len(weights)} weights from Két Symbol "
          f"{manifest['version']}; update {SOURCE_INFO.relative_to(ROOT)}")


def identifier(code):
    return "".join(part[:1].upper() + part[1:] for part in code.split("-"))


def build():
    info = json.loads(SOURCE_INFO.read_text(encoding="utf-8"))
    table = json.loads(MAP.read_text(encoding="utf-8"))
    if table["version"] != info["version"]:
        raise SystemExit(f"ketplus-map.json is {table['version']}, SOURCE.json is {info['version']}")
    sizes, weights = info["sizes"], info["weights"]
    rows = table["rows"]
    codes = sorted({r["code"] for r in rows})
    problems = []
    names = {}
    for code in codes:
        names.setdefault(identifier(code), []).append(code)
    problems += [f"identifier {k} for {v}" for k, v in names.items() if len(v) > 1 or not k.isidentifier()]
    wanted = {f"{s}/{w}/{c}.svg" for s in sizes for w in weights for c in codes}
    present = {p.relative_to(SVG).as_posix() for p in SVG.rglob("*.svg")}
    problems += [f"missing svg/{p}" for p in sorted(wanted - present)]
    problems += [f"not in ketplus-map.json: svg/{p}" for p in sorted(present - wanted)]
    for rel in sorted(wanted & present):
        if SPDX not in (SVG / rel).read_text(encoding="utf-8").splitlines()[:3]:
            problems.append(f"svg/{rel} lacks its CC BY 4.0 SPDX line")
    if not (VENDOR / LICENSE_TEXT).exists():
        problems.append(f"missing {LICENSE_TEXT}")
    if problems:
        raise SystemExit("\n".join(problems))

    label = f"Két Symbol {info['version']} ({info['commit'][:8]})"
    qrc_dir = QRC_OUT.parent
    lines = [f"<!-- Generated by tools/generate_icons.py from {label}. Do not edit. -->",
             "<!DOCTYPE RCC>", '<RCC version="1.0">', '  <qresource prefix="/ket-symbol">']
    for weight in weights:
        for size in sizes:
            for code in codes:
                path = Path("..") / ".." / ".." / SVG.relative_to(ROOT) / str(size) / weight / f"{code}.svg"
                lines.append(f'    <file alias="{weight}/{size}/{code}.svg">{path.as_posix()}</file>')
    lines += ["  </qresource>", "</RCC>"]
    assert (qrc_dir / "../../..").resolve() == ROOT
    qrc = "\n".join(lines) + "\n"

    inc = [f"// Generated by tools/generate_icons.py from {label}. Do not edit.",
           f"// Icons are CC BY 4.0: {info['attribution']}",
           "// Define the macros you need before including this file; undefined sections are skipped.",
           "//   KET_SYMBOL_SIZE(px)                         drawn master sizes",
           "//   KET_SYMBOL_WEIGHT(\"weight\")                 weights in the qrc, default first",
           "//   KET_SYMBOL_CODE(Identifier, \"code\")         Két codes in the qrc",
           "//   KET_SYMBOL_LUCIDE(\"lucide\", \"code\", \"status\") KetPlus Lucide names, status exact|equivalent",
           "// Resource path: :/ket-symbol/<weight>/<size>/<code>.svg",
           "", "#ifdef KET_SYMBOL_SIZE"]
    inc += [f"KET_SYMBOL_SIZE({s})" for s in sizes]
    inc += ["#endif", "", "#ifdef KET_SYMBOL_WEIGHT"]
    inc += [f'KET_SYMBOL_WEIGHT("{w}")' for w in weights]
    inc += ["#endif", "", "#ifdef KET_SYMBOL_CODE"]
    inc += [f'KET_SYMBOL_CODE({identifier(c)}, "{c}")' for c in codes]
    inc += ["#endif", "", "#ifdef KET_SYMBOL_LUCIDE"]
    inc += [f'KET_SYMBOL_LUCIDE("{r["lucide"]}", "{r["code"]}", "{r["status"]}")' for r in rows]
    inc += ["#endif"]
    return qrc, "\n".join(inc) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when committed outputs are stale")
    parser.add_argument("--dist", type=Path, help="vendor the KetPlus codes from an unpacked Két Symbol dist")
    args = parser.parse_args()
    if args.dist:
        info = json.loads(SOURCE_INFO.read_text(encoding="utf-8"))
        vendor(args.dist, info["sizes"], info["weights"])
        return 0
    qrc, inc = build()
    outputs = ((QRC_OUT, qrc), (INC_OUT, inc))
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale generated files: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
